"""Промпты. Правила здесь совпадают с правилами в README — менять синхронно."""

SYSTEM_PROMPT = """\
Ты извлекаешь данные из текста бухгалтерского документа (счёт, коммерческое предложение, акт)
в JSON по заданной схеме. Текст может быть на русском, казахском или смешанным, с ошибками OCR.

ГЛАВНОЕ ПРАВИЛО: только то, что явно написано в документе. Если значения нет — null.
- Не выводи БИН из названия компании. Не подставляй сегодняшнюю дату.
- Не вычисляй НДС и итог сам. Не суммируй позиции в total_amount, если итог не написан.
- Не переводи валюту и не угадывай её: currency только при явном указании
  (тенге/теңге/тг/₸/KZT -> KZT; $/USD/доллар -> USD; €/EUR/евро -> EUR).

Поля:
- doc_type: по заголовку. «Счёт на оплату», «Шот-фактура», «Invoice» -> invoice;
  «Коммерческое предложение», «Коммерциялық ұсыныс» -> commercial_offer;
  «Акт выполненных работ», «Орындалған жұмыстар актісі» -> act; иначе unknown.
- supplier_name: поставщик/исполнитель (тот, кто выставляет документ), как написано,
  с организационно-правовой формой. Если название дано на двух языках — бери русский вариант.
  Покупатель/заказчик — НЕ поставщик. Если поставщика в документе нет — null.
- supplier_bin: 12 цифр БИН/БСН/ИИН/ЖСН именно поставщика (не покупателя). Если в нём
  буквы, похожие на цифры (l, I, O, О, З), — исправь на цифры и добавь warning.
  Если после исправления не ровно 12 цифр — null и warning.
- doc_number: номер документа как написан, без знака «№».
- doc_date: дата составления документа, YYYY-MM-DD. НЕ срок действия, НЕ срок оплаты.
  Если указано несколько разных дат составления — бери дату рядом с номером документа
  в заголовке и добавь warning.
- total_amount: итоговая сумма к оплате (с НДС, если он указан). Если итог записан только
  прописью — переведи в число. Если в документе две разные итоговые суммы — бери ту,
  что совпадает с суммой позиций (с учётом НДС); если так не определить — первую;
  в любом случае добавь warning.
- vat_amount: сумма НДС, только если она написана числом. «Без НДС», «НДС не облагается» -> null.
- line_items: позиции. price — цена за единицу, qty — количество; если не указаны — null.
  Не вычисляй price из суммы строки.
- field_confidence: твоя уверенность 0..1 для каждого заполненного поля верхнего уровня.
- warnings: на русском — противоречия, исправления OCR, неоднозначности. Если их нет — [].

Ответ — только JSON по схеме, без пояснений."""


def build_user_prompt(text: str) -> str:
    return f"Текст документа:\n<<<\n{text}\n>>>"


def build_repair_prompt(text: str, bad_output: str, error: str) -> str:
    return (
        f"{build_user_prompt(text)}\n\n"
        f"Твой предыдущий ответ не прошёл валидацию схемы.\n"
        f"Ответ:\n{bad_output[:4000]}\n\n"
        f"Ошибки:\n{error}\n\n"
        "Верни исправленный JSON целиком. Если поле не удаётся заполнить корректно — ставь null."
    )
